/**
 * 生成镜头类型指南
 */
export function generateShotGuide(): string {
  return `# 镜头类型参考

## 景别
- **特写 (Close-up)**: 聚焦细节
- **中景 (Medium shot)**: 展现主体
- **全景 (Wide shot)**: 展现环境
- **远景 (Long shot)**: 宏大场景

## 运镜
- **推镜 (Dolly in)**: 镜头向前移动
- **拉镜 (Dolly out)**: 镜头向后移动
- **摇镜 (Pan)**: 水平转动
- **倾斜 (Tilt)**: 垂直转动
- **环绕 (Orbit)**: 围绕主体旋转
- **跟随 (Follow)**: 跟随移动对象
- **固定 (Static)**: 镜头不动

## 角度
- **平视**: 正常视角
- **俯拍 (High angle)**: 从上往下
- **仰拍 (Low angle)**: 从下往上
- **鸟瞰 (Aerial)**: 垂直向下
`;
}

